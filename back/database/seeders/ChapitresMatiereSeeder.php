    private function cleNiveau(Niveau $n): string
    {
        return match(true) {
            in_array($n->abbr_niveau, ['6e', '6ème'])  => '6ème',
            in_array($n->abbr_niveau, ['5e', '5ème'])  => '5ème',
            in_array($n->abbr_niveau, ['4e', '4ème'])  => '4ème',
            in_array($n->abbr_niveau, ['3e', '3ème'])  => '3ème',
            $n->abbr_niveau === '2nde'                 => '2nde',
            $n->abbr_niveau === '1ère'                 => '1ère',
            $n->abbr_niveau === 'Tle'                  => 'Tle',
            in_array($n->nom_niveau, ['Sixième'])       => '6ème',
            in_array($n->nom_niveau, ['Cinquième'])     => '5ème',
            in_array($n->nom_niveau, ['Quatrième'])     => '4ème',
            in_array($n->nom_niveau, ['Troisième'])     => '3ème',
            default                                     => $n->abbr_niveau,
        };
    }

