    public function run(): void
    {
        DB::statement('SET FOREIGN_KEY_CHECKS=0;');
        DB::table('chapitres_matiere')->truncate();
        DB::statement('SET FOREIGN_KEY_CHECKS=1;');

        $matieres = Matiere::all()->keyBy('abbr_matiere');
        $niveaux  = Niveau::orderBy('ordre')->get();

        if ($matieres->isEmpty()) {
            $this->command?->warn('Aucune matière trouvée.');
            return;
        }

        $total = 0;

        foreach ($niveaux as $niveau) {
            $cle = $this->cleNiveau($niveau);

            // Séries disponibles pour ce niveau (via les classes créées)
            $seriesDuNiveau = Serie::whereHas('classes', fn($q) => $q->where('niveau_id', $niveau->id))->get();

            foreach (self::PROGRAMMES as $abbr => $programmeParNiveau) {
                $matiere = $matieres[$abbr] ?? null;
                if (!$matiere) continue;

                // CDT : même programme pour tous les niveaux
                if ($abbr === 'CDT') {
                    $chapitres = $programmeParNiveau['6ème'] ?? null;
                    if (!$chapitres) continue;
                    foreach ($chapitres as $ordre => [$titre, $note]) {
                        ChapitreMatiere::create([
                            'matiere_id'     => $matiere->id,
                            'niveau_id'      => $niveau->id,
                            'serie_id'       => null,
                            'titre'          => $titre,
                            'ordre'          => $ordre + 1,
                            'note_direction' => $note,
                        ]);
                        $total++;
                    }
                    continue;
                }

                // Chercher des programmes spécifiques à la série (ex : '1ère_C')
                $aDesSeriesSpecifiques = false;
                foreach ($seriesDuNiveau as $serie) {
                    $cleAvecSerie = "{$cle}_{$serie->nom}";
                    if (!isset($programmeParNiveau[$cleAvecSerie])) continue;

                    $aDesSeriesSpecifiques = true;
                    foreach ($programmeParNiveau[$cleAvecSerie] as $ordre => [$titre, $note]) {
                        ChapitreMatiere::create([
                            'matiere_id'     => $matiere->id,
                            'niveau_id'      => $niveau->id,
                            'serie_id'       => $serie->id,
                            'titre'          => $titre,
                            'ordre'          => $ordre + 1,
                            'note_direction' => $note,
                        ]);
                        $total++;
                    }
                }

                // Si aucun programme spécifique trouvé → programme commun (serie_id null)
                if (!$aDesSeriesSpecifiques) {
                    $chapitres = $programmeParNiveau[$cle] ?? null;
                    if (!$chapitres) continue;
                    foreach ($chapitres as $ordre => [$titre, $note]) {
                        ChapitreMatiere::create([
                            'matiere_id'     => $matiere->id,
                            'niveau_id'      => $niveau->id,
                            'serie_id'       => null,
                            'titre'          => $titre,
                            'ordre'          => $ordre + 1,
                            'note_direction' => $note,
                        ]);
                        $total++;
                    }
                }
            }
        }

        $this->command?->info("✓ {$total} chapitres créés — programme MENET-CI avec différenciation par série ({$niveaux->count()} niveaux).");
    }
